// Provisions local passwords for the seeded accounts, so the offline provider can be signed into.
//
//   npm run auth:seed-local
//
// Supabase Auth normally owns credentials. On an offline installation there is no hosted service, so
// an operator runs this once. Generated passwords are written to .local-auth.txt, which is gitignored,
// and are shown in the summary so the operator can hand them out. Nothing here is meant for a
// production deployment: rotating or replacing this with a proper account-provisioning flow is
// outstanding work.
//
// The password is hashed with scrypt before it leaves this process. Only the encoded hash is written.

import fs from "node:fs";
import { randomBytes } from "node:crypto";
import mysql from "mysql2/promise";
import { hashPassword } from "../lib/auth/passwords.ts";

const config = JSON.parse(fs.readFileSync(new URL("../config/database.json", import.meta.url), "utf8"));
const spec = config.providers.mysql;
const env = (name) => {
  const key = spec.settings[name]?.env;
  const value = key ? process.env[key] : undefined;
  if (value !== undefined && value !== "") return value;
  return spec.settings[name]?.default;
};

// This is an operator action, so it connects with the administrative account. The application user
// deliberately cannot read cb_accounts, and provisioning credentials is not something the running
// application should be able to do.
const connection = await mysql.createConnection({
  host: env("host"),
  port: Number(env("port")),
  user: env("adminUser"),
  password: process.env[spec.settings.adminPassword.env] ?? "",
  database: env("database"),
});

function generatePassword() {
  return randomBytes(15).toString("base64url") + "#7aQ";
}

const [accounts] = await connection.query(
  "select id, email from cb_accounts order by email",
);

if (accounts.length === 0) {
  console.error("BLOCKED: no accounts found. Run npm run db:mysql:setup first.");
  process.exit(1);
}

const lines = [
  "Follow-through — local (offline) sign-in credentials",
  "",
  "Generated by npm run auth:seed-local. These exist only for the local MySQL provider.",
  "Supabase Auth is bypassed entirely here. Change or remove these before any real use.",
  "",
];
const summary = [];

for (const account of accounts) {
  const password = generatePassword();
  const hash = hashPassword(password);
  await connection.query("call cb_local_credential_set(?, ?, ?)", [account.id, hash, "scrypt"]);
  lines.push(`${account.email}`);
  lines.push(`  password: ${password}`);
  lines.push("");
  summary.push({ email: account.email, password });
}

await connection.end();

fs.writeFileSync(".local-auth.txt", lines.join("\n"), "utf8");

console.log("Local credentials provisioned");
console.log("");
for (const s of summary) console.log(`  ${s.email.padEnd(38)} ${s.password}`);
console.log("");
console.log("Written to .local-auth.txt (gitignored). Sign in at /login with any of these.");
